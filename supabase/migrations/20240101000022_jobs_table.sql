-- 5. CREATE HELPER VIEWS FOR COMMON QUERIES
-- ============================================================================

-- View: Files with their input jobs (what processing was done TO this file)
CREATE OR REPLACE VIEW "public"."files_with_input_jobs" AS
SELECT
    f.*,
    json_agg(
        json_build_object(
            'job_id', j.id,
            'nca_job_id', j.nca_job_id,
            'endpoint', j.nca_endpoint,
            'status', j.processing_status,
            'created_at', j.created_at,
            'result', j.nca_message
        ) ORDER BY j.created_at DESC
    ) FILTER (WHERE j.id IS NOT NULL) AS input_jobs
FROM "public"."files" f
LEFT JOIN "public"."job_files" jf ON jf.file_id = f.id AND jf.file_role = 'input'
LEFT JOIN "public"."jobs" j ON j.id = jf.job_id
GROUP BY f.id;

-- View: Files with their output jobs (what file was CREATED BY which job)
CREATE OR REPLACE VIEW "public"."files_with_output_jobs" AS
SELECT
    f.*,
    json_agg(
        json_build_object(
            'job_id', j.id,
            'nca_job_id', j.nca_job_id,
            'endpoint', j.nca_endpoint,
            'status', j.processing_status,
            'created_at', j.created_at
        ) ORDER BY j.created_at DESC
    ) FILTER (WHERE j.id IS NOT NULL) AS output_jobs
FROM "public"."files" f
LEFT JOIN "public"."job_files" jf ON jf.file_id = f.id AND jf.file_role = 'output'
LEFT JOIN "public"."jobs" j ON j.id = jf.job_id
GROUP BY f.id;

-- View: Jobs with their input and output files
CREATE OR REPLACE VIEW "public"."jobs_with_files" AS
SELECT
    j.*,
    (
        SELECT json_agg(
            json_build_object(
                'file_id', f.id,
                'file_name', f.file_name,
                'file_type', f.file_type,
                'url', f.url,
                'sequence_number', jf.sequence_number
            ) ORDER BY jf.sequence_number NULLS LAST
        )
        FROM "public"."job_files" jf
        JOIN "public"."files" f ON f.id = jf.file_id
        WHERE jf.job_id = j.id AND jf.file_role = 'input'
    ) AS input_files,
    (
        SELECT json_agg(
            json_build_object(
                'file_id', f.id,
                'file_name', f.file_name,
                'file_type', f.file_type,
                'url', f.url,
                'sequence_number', jf.sequence_number
            ) ORDER BY jf.sequence_number NULLS LAST
        )
        FROM "public"."job_files" jf
        JOIN "public"."files" f ON f.id = jf.file_id
        WHERE jf.job_id = j.id AND jf.file_role = 'output'
    ) AS output_files
FROM "public"."jobs" j;

COMMENT ON VIEW "public"."files_with_input_jobs" IS 'Files with aggregated list of jobs that processed them';
COMMENT ON VIEW "public"."files_with_output_jobs" IS 'Files with aggregated list of jobs that created them';
COMMENT ON VIEW "public"."jobs_with_files" IS 'Jobs with aggregated lists of input and output files';
