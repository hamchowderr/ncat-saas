-- 3. CREATE JOB_FILES JUNCTION TABLE (Many-to-Many)
-- ============================================================================
-- Links jobs to files with role tracking (input/output/reference)
-- Supports multiple input files (concatenation) and multiple output files (splitting)
CREATE TABLE IF NOT EXISTS "public"."job_files" (
    "id" UUID PRIMARY KEY DEFAULT "extensions"."uuid_generate_v4"() NOT NULL,
    "job_id" UUID NOT NULL REFERENCES "public"."jobs"("id") ON DELETE CASCADE,
    "file_id" UUID NOT NULL REFERENCES "public"."files"("id") ON DELETE CASCADE,
    "file_role" TEXT NOT NULL CHECK ("file_role" IN ('input', 'output', 'reference')),
    "sequence_number" INTEGER,
    "created_at" TIMESTAMP WITH TIME ZONE DEFAULT NOW() NOT NULL,
    UNIQUE("job_id", "file_id", "file_role", "sequence_number")
);

-- Create indexes for efficient lookups
CREATE INDEX IF NOT EXISTS "idx_job_files_job_id" ON "public"."job_files"("job_id");
CREATE INDEX IF NOT EXISTS "idx_job_files_file_id" ON "public"."job_files"("file_id");
CREATE INDEX IF NOT EXISTS "idx_job_files_role" ON "public"."job_files"("file_role");
CREATE INDEX IF NOT EXISTS "idx_job_files_job_role" ON "public"."job_files"("job_id", "file_role");

-- Add comments for documentation
COMMENT ON TABLE "public"."job_files" IS 'Many-to-many relationship between jobs and files with role tracking';
COMMENT ON COLUMN "public"."job_files"."file_role" IS 'Role of file in job: input (source), output (result), reference (additional)';
COMMENT ON COLUMN "public"."job_files"."sequence_number" IS 'Order of file in sequence (for concatenation, splitting, etc.)';

-- Enable Row Level Security
ALTER TABLE "public"."job_files" ENABLE ROW LEVEL SECURITY;

